#' @title Save the static renv dependency manifest
#' @description
#' Write literal `library()` calls for the configured packages so `{renv}`
#' detects packages that the setup script attaches dynamically. The file is
#' rewritten only when its contents change.
#' @param vec_package_names
#' Non-empty character vector of valid package names.
#' @param path_output_file
#' Path to the generated R manifest. Its folder must exist.
#' @return
#' Invisibly, `TRUE` when the file was written and `FALSE` when it was
#' already up to date.
#' @details
#' The calls are wrapped in `if (FALSE)`, so sourcing the manifest never
#' attaches anything.
#' @examples
#' \dontrun{
#' save_package_dependencies_manifest(
#'   vec_package_names = c("here", "targets"),
#'   path_output_file = here::here("R/package_dependencies.R")
#' )
#' }
save_package_dependencies_manifest <- function(vec_package_names,
                                               path_output_file) {
  assertthat::assert_that(
    base::is.character(vec_package_names),
    base::length(vec_package_names) > 0L,
    isFALSE(base::anyNA(vec_package_names)),
    msg = "`vec_package_names` must be a non-empty character vector."
  )

  assertthat::assert_that(
    base::is.character(path_output_file),
    base::length(path_output_file) == 1L,
    !base::is.na(path_output_file),
    base::nzchar(path_output_file),
    msg = "`path_output_file` must be a single non-empty path."
  )

  vec_invalid_names <-
    vec_package_names[
      !stringr::str_detect(
        string = vec_package_names,
        pattern = "^[A-Za-z][A-Za-z0-9.]*$"
      )
    ]

  assertthat::assert_that(
    base::length(vec_invalid_names) == 0L,
    msg = stringr::str_glue(
      "Invalid package name(s): ",
      "{stringr::str_c(vec_invalid_names, collapse = ', ')}."
    )
  )

  dir_output <-
    base::dirname(path_output_file)

  assertthat::assert_that(
    base::dir.exists(dir_output),
    msg = stringr::str_glue("Output directory does not exist: {dir_output}")
  )

  vec_package_names_unique <-
    base::unique(vec_package_names)

  vec_generated_lines <-
    c(
      "# Generated by `R/___setup_project___.R` from `packages` in",
      "#   `config.yml`. Do not edit it manually.",
      "# Literal library calls let renv detect dynamically attached packages.",
      "if (",
      "  FALSE",
      ") {",
      stringr::str_c("  library(", vec_package_names_unique, ")"),
      "}"
    )

  vec_current_lines <- NULL

  if (
    base::file.exists(path_output_file)
  ) {
    vec_current_lines <-
      base::readLines(
        con = path_output_file,
        warn = FALSE,
        encoding = "UTF-8"
      )
  }

  if (
    base::identical(vec_generated_lines, vec_current_lines)
  ) {
    return(invisible(FALSE))
  }

  base::writeLines(
    text = vec_generated_lines,
    con = path_output_file,
    sep = "\n",
    useBytes = TRUE
  )

  return(invisible(TRUE))
}
